// Update Data Grafik Berdasarkan Data Pasien Terkini
function updateCharts(filtered) {
  if (!donutChartInstance || !barChartInstance) return;

  // Hitung Distribusi Status Progres Klien
  let countOngoing = 0;
  let countSelesai = 0;
  let countDropout = 0;

  filtered.forEach((p) => {
    const stProgres = String(p.statusProgres || "ON GOING").toUpperCase().trim();
    if (stProgres.includes("DROP") || stProgres.includes("DO")) {
      countDropout++;
    } else if (stProgres.includes("SELESAI") || stProgres.includes("PULIH")) {
      countSelesai++;
    } else {
      countOngoing++;
    }
  });

  const totalStatus = countOngoing + countSelesai + countDropout;
  const pctOngoing = totalStatus === 0 ? 0 : Math.round((countOngoing / totalStatus) * 100);
  const pctSelesai = totalStatus === 0 ? 0 : Math.round((countSelesai / totalStatus) * 100);
  const pctDropout = totalStatus === 0 ? 0 : Math.max(0, 100 - pctOngoing - pctSelesai);

  // Update Dataset Donut
  donutChartInstance.data.datasets[0].data = [countOngoing, countSelesai, countDropout];
  donutChartInstance.options.plugins.tooltip.callbacks.label = (ctx) => {
    const val = ctx.raw;
    const pct = totalStatus === 0 ? 0 : Math.round((val / totalStatus) * 100);
    return ` ${ctx.label}: ${val} Klien (${pct}%)`;
  };
  donutChartInstance.update();

  // Update Teks Legenda Donut
  const legOngoing = document.getElementById("legOngoing");
  const legSelesai = document.getElementById("legSelesai");
  const legDropout = document.getElementById("legDropout");

  if (legOngoing) legOngoing.innerHTML = `<i class="dot dot-blue"></i> On Going (${pctOngoing}%)`;
  if (legSelesai) legSelesai.innerHTML = `<i class="dot dot-green"></i> Selesai / Pulih (${pctSelesai}%)`;
  if (legDropout) legDropout.innerHTML = `<i class="dot dot-rose"></i> Drop Out (${pctDropout}%)`;

  // Hitung Sebaran per Kecamatan
  const kecList = ["Buleleng", "Sukasada", "Seririt", "Gerokgak", "Banjar", "Sawan", "Kubutambahan", "Busungbiu", "Tejakula"];
  const kecCounts = kecList.map((kec) =>
    filtered.filter((p) => (p.kecamatan || "").toLowerCase() === kec.toLowerCase()).length
  );

  const maxVal = Math.max(...kecCounts, 3);
  barChartInstance.options.scales.y.suggestedMax = maxVal + 1;
  barChartInstance.data.labels = kecList;
  barChartInstance.data.datasets[0].data = kecCounts;
  barChartInstance.data.datasets[0].backgroundColor = kecCounts.map((v) => (v > 0 ? "#0f223f" : "#cbd5e1"));
  barChartInstance.update();
}

// Sinkronisasi Real-Time dari monitoring-pasien.html
function initRealtimeSync() {
  // 1. Dengarkan event 'storage' (terpicu saat tab monitoring mengubah localStorage)
  window.addEventListener("storage", (e) => {
    if (e.key === "simRehabPatients") {
      updateDashboard();
    }
  });

  // 2. Refresh saat tab dashboard aktif kembali (focus)
  window.addEventListener("focus", () => {
    updateDashboard();
  });

  // 3. Polling ringan setiap 1,5 detik untuk mendeteksi perubahan seketika
  setInterval(() => {
    updateDashboard();
  }, 1500);
}

function initUserInfo(user) {
  const roleLabels = {
    petugas_rehab: "Petugas Rehabilitasi",
    super_user: "Petugas / Super User",
    admin: "Administrator Sistem",
    dokter: "Dokter / Tenaga Medis",
  };

  const roleEl = document.getElementById("userRole");
  const idEl = document.getElementById("userId");

  if (roleEl) {
    roleEl.textContent = roleLabels[user.role] || "Petugas / Super User";
  }
  if (idEl) {
    const displayName = user.username || "2121";
    idEl.textContent = `ID: ${displayName} (Seksi Rehab)`;
  }
}

function initDate() {
  const dateEl = document.getElementById("currentDate");
  if (!dateEl) return;

  const now = new Date();
  const options = { day: "2-digit", month: "long", year: "numeric" };
  dateEl.textContent = now.toLocaleDateString("id-ID", options);
}

function initLogout() {
  const logoutBtn = document.getElementById("logoutBtn");
  if (!logoutBtn) return;

  logoutBtn.addEventListener("click", (e) => {
    e.preventDefault();
    localStorage.removeItem("simRehabUser");
    sessionStorage.removeItem("simRehabUser");
    window.location.href = "index.html";
  });
}
