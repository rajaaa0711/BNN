// Ambil data pasien dari localStorage (sinkron dengan monitoring-pasien.js)
function getPatients() {
  const data = localStorage.getItem("simRehabPatients");
  if (!data) {
    localStorage.setItem("simRehabPatients", JSON.stringify(defaultSeedPatients));
    return defaultSeedPatients;
  }
  try {
    const parsed = JSON.parse(data);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem("simRehabPatients", JSON.stringify(defaultSeedPatients));
      return defaultSeedPatients;
    }
    return parsed;
  } catch (e) {
    return defaultSeedPatients;
  }
}

// Inisialisasi Event Filter Dropdown
function initFilters() {
  const filters = ["filterTahun", "filterGender", "filterKecamatan", "filterStatus"];
  filters.forEach((id) => {
    const el = document.getElementById(id);
    if (el) {
      el.addEventListener("change", () => {
        updateDashboard();
      });
    }
  });
}

// Filter data pasien sesuai dropdown yang aktif
function getFilteredPatients() {
  const allPatients = getPatients();
  const tahun = document.getElementById("filterTahun")?.value || "semua";
  const gender = document.getElementById("filterGender")?.value || "semua";
  const kecamatan = document.getElementById("filterKecamatan")?.value || "semua";
  const status = document.getElementById("filterStatus")?.value || "semua";

  return allPatients.filter((p) => {
    // 1. Filter Tahun
    if (tahun !== "semua") {
      const pTahun = p.tahunRehab || (p.tglKedatangan ? p.tglKedatangan.substring(0, 4) : "2026");
      if (pTahun !== tahun) return false;
    }

    // 2. Filter Gender
    if (gender !== "semua") {
      if ((p.gender || "laki").toLowerCase() !== gender.toLowerCase()) return false;
    }

    // 3. Filter Kecamatan
    if (kecamatan !== "semua") {
      if ((p.kecamatan || "").toLowerCase() !== kecamatan.toLowerCase()) return false;
    }

    // 4. Filter Status
    if (status !== "semua") {
      const stProgres = String(p.statusProgres || "ON GOING").toUpperCase().trim();
      const isDO = stProgres.includes("DROP") || stProgres.includes("DO");
      const isSelesai = stProgres.includes("SELESAI") || stProgres.includes("PULIH");
      const isOngoing = !isDO && !isSelesai;
      const isRawatInap = String(p.statusRawat || "").toLowerCase().includes("inap");
      const isRawatJalan = !isRawatInap;

      if (status === "ongoing" && !isOngoing) return false;
      if (status === "selesai" && !isSelesai) return false;
      if (status === "dropout" && !isDO) return false;
      if (status === "rawat_jalan" && (!isOngoing || !isRawatJalan)) return false;
      if (status === "rawat_inap" && (!isOngoing || !isRawatInap)) return false;
    }

    return true;
  });
}

// Update Statistik & Grafik di Dashboard Secara Menyeluruh
function updateDashboard() {
  const filtered = getFilteredPatients();

  // Hitung Kartu Statistik
  const elTotal = document.getElementById("statTotal");
  const elJalan = document.getElementById("statRawatJalan");
  const elInap = document.getElementById("statRawatInap");
  const elSelesai = document.getElementById("statSelesai");
  const elDo = document.getElementById("statDropout");

  const total = filtered.length;
  let jalan = 0;
  let inap = 0;
  let selesai = 0;
  let dropout = 0;

  filtered.forEach((p) => {
    const stProgres = String(p.statusProgres || "ON GOING").toUpperCase().trim();
    const isDO = stProgres.includes("DROP") || stProgres.includes("DO");
    const isSelesai = stProgres.includes("SELESAI") || stProgres.includes("PULIH");
    const isRawatInap = String(p.statusRawat || "").toLowerCase().includes("inap");

    if (isDO) {
      dropout++;
    } else if (isSelesai) {
      selesai++;
    } else if (isRawatInap) {
      inap++;
    } else {
      jalan++;
    }
  });

  if (elTotal) elTotal.textContent = total;
  if (elJalan) elJalan.textContent = jalan;
  if (elInap) elInap.textContent = inap;
  if (elSelesai) elSelesai.textContent = selesai;
  if (elDo) elDo.textContent = dropout;

  // Update Charts
  updateCharts(filtered);
}

